#!/usr/bin/env bash
# Sculpture Trail Visitor Map — project setup.
# Installs Python dependencies, writes a local .env if missing, then creates and
# seeds the SQLite database. It never starts the HTTP server (that is
# `python3 app.py`), so it always exits.
set -euo pipefail
cd "$(dirname "$0")"

PYTHON="${PYTHON:-python3}"

echo "==> Installing Python dependencies"
"$PYTHON" -m pip install --upgrade pip setuptools wheel
"$PYTHON" -m pip install -r requirements.txt

echo "==> Preparing local configuration"
if [ ! -f .env ]; then
  secret="$("$PYTHON" -c 'import secrets; print(secrets.token_hex(32))')"
  {
    echo "# Generated by install.sh. Not committed."
    echo "SESSION_SECRET=${secret}"
    echo "SCULPTURE_DB_PATH=./trail.db"
    echo "PORT=8000"
    echo "SESSION_COOKIE_SECURE=false"
  } > .env
  chmod 600 .env
  echo "    wrote .env with a generated SESSION_SECRET"
else
  echo "    .env already present, leaving it untouched"
fi

echo "==> Creating the SQLite schema and seeding demo data"
"$PYTHON" seed.py

echo "==> Verifying the application modules import cleanly"
"$PYTHON" -c "import app, auth, db, repo, seed, views, routes; print('    modules import cleanly')"

echo
echo "Setup complete. Start the server with:"
echo "    python3 app.py            # http://0.0.0.0:\${PORT:-8000}"
echo "Demo accounts are printed on the sign-in page and in README.md."
